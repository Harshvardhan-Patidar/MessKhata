create or replace function public.consume_plate(
  p_customer_id uuid,
  p_count integer default 1,
  p_note text default 'Meal consumed'
)
returns public.customers
language plpgsql
security definer
set search_path = public
as $$
declare
  c public.customers;
begin
  -- Lock the row for correct concurrent behavior
  select * into c
  from public.customers
  where id = p_customer_id
    and admin_id = auth.uid()
  for update;

  if not found then
    raise exception 'Customer not found or not owned by admin';
  end if;

  if c.remaining_plates is null or c.remaining_plates < p_count then
    raise exception 'Not enough remaining plates';
  end if;

  -- Check expiry for fixed plans
  if c.current_plan_type = 'fixed_plates'
     and c.plan_expiry_date is not null
     and c.plan_expiry_date < now() then
    raise exception 'Plan has already expired';
  end if;

  update public.customers
    set remaining_plates = remaining_plates - p_count,
        last_visit_at    = now(),
        updated_at       = now()
  where id = p_customer_id
  returning * into c;

  insert into public.logs (admin_id, customer_id, plates_deducted, note)
  values (auth.uid(), p_customer_id, p_count, p_note);

  return c;
end;
$$;



create or replace function public.renew_plan(
  p_customer_id uuid,
  p_additional_plates integer,
  p_new_expiry timestamptz default null,
  p_note text default 'Plan renewed'
)
returns public.customers
language plpgsql
security definer
set search_path = public
as $$
declare
  c public.customers;
begin
  select * into c
  from public.customers
  where id = p_customer_id
    and admin_id = auth.uid()
  for update;

  if not found then
    raise exception 'Customer not found or not owned by admin';
  end if;

  update public.customers
    set total_plates     = coalesce(total_plates, 0) + p_additional_plates,
        remaining_plates = coalesce(remaining_plates, 0) + p_additional_plates,
        plan_expiry_date = p_new_expiry,
        status           = 'active',
        updated_at       = now()
  where id = p_customer_id
  returning * into c;

  insert into public.logs (admin_id, customer_id, plates_deducted, note)
  values (auth.uid(), p_customer_id, 0, p_note);

  return c;
end;
$$;

create or replace function public.auto_update_expired_and_archived()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Mark expired: 0 plates OR expiry passed
  update public.customers
  set status = 'expired',
      updated_at = now()
  where admin_id = auth.uid()
    and status = 'active'
    and (
      (current_plan_type = 'fixed_plates' and remaining_plates <= 0)
      or (plan_expiry_date is not null and plan_expiry_date < now())
    );

  -- Auto‑archive: expired for > 10 days
  update public.customers
  set status = 'archived',
      updated_at = now()
  where admin_id = auth.uid()
    and status = 'expired'
    and plan_expiry_date is not null
    and plan_expiry_date < (now() - interval '10 days');
end;
$$;


